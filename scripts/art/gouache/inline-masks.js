#!/usr/bin/env node
/* Inlines the small brush masks (nav glyphs, stroke, dab) into css/lp-gouache.css as data URIs.
   Why: on a first visit the service worker precaches hundreds of files and six tiny mask requests
   queue behind them — the navigation stood without glyphs for seconds. Run after run.js repaints
   any of these files:  node scripts/art/gouache/inline-masks.js */
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..", "..", "..");
const ART = path.join(ROOT, "public", "art", "gouache");
const CSS = path.join(ROOT, "public", "css", "lp-gouache.css");
const uri = (name) => 'url("data:image/webp;base64,' + fs.readFileSync(path.join(ART, name + ".webp")).toString("base64") + '")';

let css = fs.readFileSync(CSS, "utf8");
const BEGIN = "  /* inline-masks:begin (generated by scripts/art/gouache/inline-masks.js) */";
const END = "  /* inline-masks:end */";
const names = ["stroke", "dab", "nav-room", "nav-mediatheque", "nav-news", "nav-studio", "nav-review", "nav-dictionary"];
const block = [BEGIN].concat(names.map((n) => `  --lp-m-${n}: ${uri(n)};`), [END]).join("\n");

if (css.includes(BEGIN)) css = css.slice(0, css.indexOf(BEGIN)) + block + css.slice(css.indexOf(END) + END.length);
else {
  const anchor = "  --lp-mast: 250px;";
  if (!css.includes(anchor)) throw new Error("anchor not found");
  css = css.replace(anchor, block + "\n" + anchor);
}
for (const n of names) css = css.split(`url("/art/gouache/${n}.webp")`).join(`var(--lp-m-${n})`);
fs.writeFileSync(CSS, css);
console.log("inlined", names.length, "masks;", (fs.statSync(CSS).size / 1024).toFixed(0), "KB css");
