#!/usr/bin/env node
"use strict";
// Builds public/js/translit-cluster-words.js (O-033, 2026-09-29): the words whose first letter ב/כ
// with sheva is a root letter read in a cluster (bgadim, ktiva), not a prefix (bemahalakh).
// Source: every Pealim form starting with ב/כ + sheva whose own Pealim transcription runs that
// letter into the next consonant (бгадим), plus function words Pealim lacks. The modern-reading
// pass reads every other such ב/כ as a prefix with "e" (owner's decision for unknown words).
//   node scripts/premium/build-translit-cluster-words.js          write the module
//   node scripts/premium/build-translit-cluster-words.js --check  exit 1 if it is stale
const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const REPO = path.join(__dirname, "..", "..");
const DICT = path.join(REPO, "public", "data", "inflection", "pealim-infl-v12.json.gz");
const OUT = path.join(REPO, "public", "js", "translit-cluster-words.js");

const SHEVA = "ְ";
const FINAL = { "ך": "כ", "ם": "מ", "ן": "נ", "ף": "פ", "ץ": "צ" };
// Spoken as a cluster although Pealim has no paradigm for them.
const FUNCTION_WORDS = ["כְּבָר", "כְּדֵי", "כְּמוֹ", "כְּלוּם", "כְּלוֹמַר", "בְּלִי", "כְּלַפֵּי", "כְּפִי"];

// Same key as translit-modern-reading.js: letters only, final forms medial, doubled ו/י once.
function skeleton(word) {
  return String(word).normalize("NFD").replace(/[^א-ת]/g, "").split("").map((c) => FINAL[c] || c).join("")
    .replace(/וו/g, "ו").replace(/יי/g, "י");
}

function startsWithShevaBetKaf(word) {
  const m = String(word).normalize("NFD").match(/^([בכ])([֑-ׇ]*)[א-ת]/);
  return !!m && m[2].indexOf(SHEVA) >= 0;
}

// Pealim points the defective spelling (בְּרֵכָה); subtitles and modern text write the full one
// (בריכה). Each form is also keyed in full spelling: י after hiriq or tsere, ו after holam or
// qubuts, unless that letter is already there or the next letter closes the syllable.
function fullSpelling(word) {
  const units = [];
  for (const ch of String(word).normalize("NFD")) {
    if (/[א-ת]/.test(ch) || !units.length) units.push({ ch, marks: "" });
    else units[units.length - 1].marks += ch;
  }
  let out = "";
  units.forEach((u, i) => {
    out += u.ch;
    const next = units[i + 1];
    if (!next) return;
    if (/[ִֵ]/.test(u.marks) && next.ch !== "י" && next.marks.indexOf(SHEVA) < 0 && next.marks.indexOf("ּ") < 0) out += "י";
    else if (/[ֹֻ]/.test(u.marks) && next.ch !== "ו") out += "ו";
  });
  return skeleton(out);
}

function buildClusterWords(paradigms) {
  const list = paradigms || JSON.parse(zlib.gunzipSync(fs.readFileSync(DICT)).toString("utf8")).paradigms;
  const words = new Set(FUNCTION_WORDS.map(skeleton));
  for (const p of list) {
    for (const cell of Object.values(p.cells || {})) {
      const he = String(cell.he || "").split(/[\s־-]+/).filter(Boolean);
      const ru = String(cell.translit || "").toLowerCase().split(/[\s-]+/).filter(Boolean);
      if (he.length !== ru.length) continue;
      he.forEach((w, i) => {
        // Pealim writes the spoken sheva as э/е right after the letter (бэ-, кеhе).
        if (startsWithShevaBetKaf(w) && /^[бк][^эеаиоу]/.test(ru[i])) {
          words.add(skeleton(w));
          words.add(fullSpelling(w));
        }
      });
    }
  }
  return [...words].sort();
}

function renderModule(words) {
  return [
    "// GENERATED by scripts/premium/build-translit-cluster-words.js from Pealim — do not edit.",
    "// Words whose first ב/כ with sheva is a root letter read in a cluster (bgadim, kvar), keyed by",
    "// letters only: final forms medial, doubled ו/י once. Used by translit-modern-reading.js.",
    "(function (root) {",
    "  var words = \"" + words.join(" ") + "\".split(\" \");",
    "  if (typeof module === \"object\" && module.exports) module.exports = words;",
    "  if (root) root.TranslitClusterWords = words;",
    "})(typeof globalThis !== \"undefined\" ? globalThis : this);",
    "",
  ].join("\n");
}

module.exports = { buildClusterWords, renderModule, skeleton };

if (require.main === module) {
  const text = renderModule(buildClusterWords());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== text) { console.error("translit-cluster-words.js is stale; run without --check"); process.exit(1); }
    console.log("translit-cluster-words.js is current");
  } else {
    fs.writeFileSync(OUT, text);
    console.log("wrote " + path.relative(REPO, OUT) + " (" + text.length + " bytes)");
  }
}
